/* Esse programa mostra o uso de comentários em várias linhas
 * e mostra também o uso de comentários em uma única linha
 *
 * Questão 03 - Primeiro programa documentado
 ****************************************************************/

/* exercicio03.c */

#include <stdio.h>  /* Para printf() */
#include <stdlib.h> /* Para system() */

int main()                          /* Função main */
{                                   /* início do corpo da função main */
    printf("Primeiro programa.\n"); /* Chamada à função printf */
    system("PAUSE");                /* Chamada à função system (pausa o console no Windows) */
    return 0;                       // retorna 0 ao sistema: execução sem erros
}                                   /* Fim do corpo da função main */
